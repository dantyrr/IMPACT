#!/usr/bin/env python3
"""Write docs/js/affil-places.js: the place tables of src/pipeline/affil_location.py
for the browser-side parser (docs/js/affil-location.js). Re-run after editing them."""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.pipeline import affil_location as al

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "js", "affil-places.js")


def main():
    tables = {
        "places": {" ".join(k): list(v) for k, v in al._PLACES.items()},
        "countryKeys": sorted(" ".join(k) for k in al._COUNTRY_KEYS),
        "codes": {k: list(v) for k, v in al._CODES.items()},
        "ap": {" ".join(k): v for k, v in al._AP_KEYS.items()},
        "zipRanges": al._ZIP_RANGES,
        "maxPlace": al._MAX_PLACE,
        "georgiaCountry": sorted(al._GEORGIA_COUNTRY),
        "lebanonNH": sorted(al._LEBANON_NH),
    }
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/build_affil_places_js.py from src/pipeline/affil_location.py.\n")
        f.write("// Do not edit by hand.\n")
        f.write(f"const AFFIL_PLACES = {json.dumps(tables, separators=(',', ':'))};\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT):,} bytes)")


if __name__ == "__main__":
    main()
